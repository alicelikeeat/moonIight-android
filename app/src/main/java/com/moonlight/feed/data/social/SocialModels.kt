package com.moonlight.feed.data.social

import java.util.UUID

/** Globally unique id (UUID v4) for users, conversations, messages, moments, comments and attachments — safe to sync later. */
fun newId(): String = UUID.randomUUID().toString()

/**
 * A person in 朋友圈 / 消息. Virtual friends are written by the user ([isVirtual] = true).
 * Real accounts from a future chat server coexist with [isVirtual] = false and [remoteUserId] set.
 */
data class Contact(
    val id: String = newId(),
    val name: String,
    val bio: String = "",
    /** Local image file (copied into app storage) or null → generated monogram. */
    val avatarPath: String? = null,
    /** Index into the monogram palette. */
    val avatarColor: Int = 0,
    /** [avatarPath] is a video (plays small, muted, looping; first frame when animation is off). */
    val avatarVideo: Boolean = false,
    /** 朋友圈 cover (self) / profile background (friends): copied photo or video in app storage. */
    val coverPath: String? = null,
    val coverVideo: Boolean = false,
    /** Reposition/zoom chosen in the editor ("x,y,scale"; null → default upper-third bias). */
    val avatarFocus: com.moonlight.feed.data.MediaFocus? = null,
    val coverFocus: com.moonlight.feed.data.MediaFocus? = null,
    /** The previous avatar / cover, kept when it is replaced or 恢复默认 — 用回 restores it; only 删除 forgets it. */
    val prevAvatar: SavedMedia? = null,
    val prevCover: SavedMedia? = null,
    val isVirtual: Boolean = true,
    val isSelf: Boolean = false,
    val remoteUserId: String? = null,
    val autoReplyOn: Boolean = false,
    val autoReplies: List<String> = emptyList(),
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = createdAt,
)

enum class AttachmentKind { IMAGE, VIDEO, EMBED }

/** A media reference. Locally it points at a file / library entry; after upload it gains [remoteUrl] + [remoteId]. */
data class Attachment(
    val id: String = newId(),
    val kind: AttachmentKind,
    val libraryEntryId: String? = null,
    val localPath: String? = null,
    val coverUrl: String? = null,
    val remoteUrl: String? = null,
    val remoteId: String? = null,
    val mime: String? = null,
    val sizeBytes: Long = 0,
    val title: String = "",
) {
    /** What the image loader should draw (file, cover, or remote url). */
    fun model(): Any? = localPath?.let { java.io.File(it) } ?: coverUrl ?: remoteUrl
}

data class Comment(
    val id: String = newId(),
    val authorId: String,
    val text: String,
    val replyToId: String? = null,
    val createdAt: Long = System.currentTimeMillis(),
)

data class Moment(
    val id: String = newId(),
    val authorId: String,
    val text: String = "",
    val attachments: List<Attachment> = emptyList(),
    val createdAt: Long = System.currentTimeMillis(),
    val editedAt: Long? = null,
    val likes: List<String> = emptyList(),
    /** 踩 — same "who" model as [likes]; one person is in at most one of the two lists. */
    val dislikes: List<String> = emptyList(),
    val comments: List<Comment> = emptyList(),
    /** v5.0: 朋友圈自动播放 › 只播指定的 — the user marked this post 自动播放 (⋯ sheet). */
    val autoplay: Boolean = false,
)

/** Delivery state of a chat message (local-only messages stay [LOCAL] / [SENT] until a server exists). */
enum class MessageStatus { LOCAL, SENDING, SENT, DELIVERED, READ, FAILED }

data class Conversation(
    val id: String = newId(),
    val memberIds: List<String>,
    val title: String? = null,
    val isGroup: Boolean = memberIds.size > 2,
    /** true → routed through [RemoteTransport] (server chat); false → offline/virtual. */
    val remote: Boolean = false,
    val remoteId: String? = null,
    val pinned: Boolean = false,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = createdAt,
    /** Local read marker for the unread badge: messages from others after this are unread. */
    val readAt: Long = 0,
)

data class Message(
    val id: String = newId(),
    val conversationId: String,
    val senderId: String,
    val text: String = "",
    val attachments: List<Attachment> = emptyList(),
    /** Client clock when written (user may back-date). */
    val createdAt: Long = System.currentTimeMillis(),
    /** Server-assigned ordering timestamp; null until a server acknowledges. */
    val serverAt: Long? = null,
    val status: MessageStatus = MessageStatus.LOCAL,
    /** Generated by a friend's preset auto-reply (never triggers further auto-replies). */
    val auto: Boolean = false,
    val error: String? = null,
)

data class SocialState(
    val selfId: String,
    val contacts: List<Contact>,
    val moments: List<Moment> = emptyList(),
    val conversations: List<Conversation> = emptyList(),
    val messages: List<Message> = emptyList(),
    val schema: Int = SCHEMA,
) {
    val self: Contact get() = contacts.first { it.id == selfId }
    fun contact(id: String): Contact? = contacts.firstOrNull { it.id == id }
    val friends: List<Contact> get() = contacts.filter { !it.isSelf }
    fun messagesOf(convId: String) = messages.filter { it.conversationId == convId }.sortedBy { it.serverAt ?: it.createdAt }
    fun lastMessage(convId: String) = messages.filter { it.conversationId == convId }.maxByOrNull { it.serverAt ?: it.createdAt }
    fun momentsBy(id: String) = moments.filter { it.authorId == id }.sortedByDescending { it.createdAt }
    val timeline: List<Moment> get() = moments.sortedByDescending { it.createdAt }
    fun unread(convId: String): Int {
        val c = conversations.firstOrNull { it.id == convId } ?: return 0
        if (selfId !in c.memberIds) return 0 // friend↔friend chats you author yourself never count
        return messages.count { it.conversationId == convId && it.senderId != selfId && it.createdAt > c.readAt }
    }
    val totalUnread: Int get() = conversations.sumOf { unread(it.id) }

    companion object {
        const val SCHEMA = 2
        fun fresh(): SocialState {
            val me = Contact(name = "我", isSelf = true, isVirtual = false, avatarColor = 0, bio = "")
            return SocialState(me.id, listOf(me))
        }
    }
}


/** A stored photo/video copy with its position. */
data class SavedMedia(val path: String, val video: Boolean, val focus: com.moonlight.feed.data.MediaFocus? = null)
